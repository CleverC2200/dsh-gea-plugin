/**
 * "这一轮用户有没有页面意图"的判定。
 *
 * 背景（用户要求 + 线上实测）：页面开着的时候，位置提示与通道顺序都在引导模型"读这一屏"，
 * 于是它一进来就先拉一份快照——而快照可能带整屏的行与字段，上下文当场被撑起来。
 * 现在改成：**默认不读页面**，只有用户这一轮明确表达了页面意图（读这一屏、看这几行、
 * 展开、选中、这单……）才允许生成快照。
 *
 * 判据只看用户原话里的页面指代，不认识任何具体业务；一处判、三处用
 * （位置提示、通道顺序、页面快照工具的门禁）。
 */

/** 页面指代词：出现任意一个就算"用户在看/要操作这一屏"。 */
export const PAGE_INTENT_WORDS = [
  "这一屏",
  "这屏",
  "当前屏",
  "这一页",
  "这页",
  "本页",
  "当前页",
  "页面上",
  "当前界面",
  "界面上",
  "当前面板",
  "这几行",
  "这几条",
  "这几家",
  "这些行",
  "当前列表",
  "列表里的",
  "列表里",
  "表格里的",
  "表格里",
  "表里的",
  "屏幕上的",
  "屏幕上",
  "我看到的",
  "当前选中",
  "选中的",
  "选中行",
  "勾选的",
  "展开",
  "这一单",
  "这单",
  "这张单",
  "这个单",
  "当前单",
  "这版",
  "当前版本",
  "当前节点",
  "这个节点",
] as const;

/**
 * 用户这句话里的页面意图词；没有就返回 undefined（默认不读页面）。
 * `question` 为空时也返回 undefined——没有原话就不猜。
 */
export function pageIntentOf(question: string | undefined): string | undefined {
  const text = question?.replace(/\s+/g, " ").trim();
  if (!text) return undefined;
  return PAGE_INTENT_WORDS.find((word) => text.includes(word));
}
