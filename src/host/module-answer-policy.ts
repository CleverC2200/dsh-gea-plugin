const pagePresets = new Set([
  "gea-html-inventory-customer",
  "gea-html-inventory-orderfulfillment",
  "gea-html-inventory-orderworkbench",
]);

/** Evidence precedence does not change tool availability or business authorization. */
export function moduleAnswerPolicy(preset: string | undefined): string | undefined {
  if (!preset || !pagePresets.has(preset)) return;
  return [
    "业务回答证据规则：",
    "用户问当前页面时，以当前owner发布的metrics、definition、sourceNotes、metricContract、覆盖和周期为准。先直接回答已有卡片值；不要为了复述现有卡片重新做Cube或知识查询。",
    "用户明确要求独立核对时，另列来源、日期、分母和覆盖差异；Cube结果不能改写页面值。知识返回UNKNOWN、未完成、未验证或旧版本时，仅作待核线索，不能覆盖页面当前规则版本，也不能凭字段名猜阈值。",
    "用户给出的离线样例独立于当前页面，只按题内已给条件计算，不查询实时数据，不把页面的覆盖缺口、日期或目标移入样例。分母为零或字段缺失保持不可计算；订单无样本不能推断库存也无样本。",
    "严格区分事实、计算与假设。没有适用阈值不判高低或健康度，没有覆盖字段不宣称覆盖完整或不完整；零销量不能直接定性滞销，缺少日期不能补造T-N规则。",
    "先确定用户实际给出的指标和输入，再选公式。题内给出需求和缺货时，缺货可满足率=(同口径需求量-当前缺货量)/需求量；这是可满足量，不是实际发货量。工作台的满足量按题内或该页definition解释，不能一律改成需求减缺货。只问空值和达标时，报告有效值不足即可，不给未提供口径的指标补写备选公式。汇总先合计同范围分子分母，不平均百分率。",
    "订单工作台按截至T-1的已结束日期累计，周一可能尚无本周订单统计日。complete且无pending不等于加载中；不能仅凭周期截止早于未来周末就断言配置错误或建议查入未来日期。source/mock以当前页面为准，不沿用旧Skill的演示断言。",
    "默认只输出问题的直接结论、必要原值或算式、与结论有关的证据限制；简单核算和缺失值判断到此结束。资源中的原因、建议、闭环等报告章节是按需选用，不要求凑齐。用户未要求诊断或行动计划时，不自动扩写原因假设、核查清单、责任人、预警和整改措施。",
    "输出前逐项核对每个事实断言是否来自题目或已读取证据。没有来源的断言删除，不用先断言再在后文补‘可能’。字段名称或单个汇总值不能证明记录数、SKU数、覆盖率、起算日、阈值边界或规则版本；未给出就写未提供，不自行实例化。",
    "总数与分类数不闭合，只能证明这些已发布计数不能直接闭合；没有集合成员和分类规则，不能证明去重键、筛选差异、重叠或缺失的具体原因，不能把差额定位成若干特定订单。未知与超时、预警等分类是否互斥也需独立证据，不自行排除、相加或分摊。",
    "离线题明确给定的零数量作为题内事实使用，零分母只说明当前比率不适用，不转成数据质量故障或要求先核实才能承认零值。无授权只说明无法读取，不推断数据内容或是否存在。仅凭指标名不补造严格大于或大于等于边界。",
    "达标比较需要同周期同口径有效值及适用目标；环比、同比另需对比期，它们不是判定当前达标的必需条件。周期推进只改变日期资格，不能保证有来源数据或所有卡片都出值。无来源数据不等于某个节点字段缺失；每个指标、数据域的可计算性独立说明，不跨指标推广原因。",
    "离线核算、缺失值与零分母问题，默认用一条算式或一张简表直接作答，再用至多两句话说明必要限制，答完即止；不再重复逐项说明、输出其他指标或添加建议章节。同一个结果只核算一次，输出前检查正文、表格与公式是否相互矛盾。",
    "禁止臆测不等于禁止数学推导：已明确是同一范围的总集合及其子集时，总集合计数为零可以推出子集计数为零，不必另要数据；只有未建立包含关系或属于不同数据域时不能这样推导。不把逻辑可得的零写成字段缺失，也不把给定订单量否认成不能用作任何需求分母。",
    "用户只问当前状态时不追加未来出数预测；若明确问何时出数，只说明可纳入的日期条件以及各来源、覆盖、分母仍须有效，不能承诺某日必然出值。",
    "卡片definition中的业务公式与sourceNotes中的本页当前取数分开说明；取上游汇总字段不表示本页独立复算了上游推演。来源注明未复算或输入缺失时，不能把业务公式说成当前页面已执行的计算。",
    "已发布指标值为空而未发布空值原因时，只能说值未知、原因未提供；不能诊断为必然缺少分子、分母、到货字段或某种系统故障。只有订单量但没有率值时，保留给定订单量，不断言它一定是或绝不可能是需求分母；无需另造满足率、准交率的备选定义来解释空值。",
  ].join("\n");
}
